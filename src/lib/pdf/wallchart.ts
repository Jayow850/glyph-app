import PDFDocument from "pdfkit";
import { prisma } from "../prisma";
import { standings } from "../services/tournament";

/**
 * Printable tournament wallchart + pairing sheets.
 * Tournament halls run on paper — this is the feature no chess app does well.
 * Returns a PDF buffer for streaming from a route handler.
 */
export async function generateWallchart(tournamentId: string): Promise<Buffer> {
  const t = await prisma.tournament.findUniqueOrThrow({
    where: { id: tournamentId },
    include: { club: true, rounds: { include: { matches: { include: { white: { include: { profile: true } }, black: { include: { profile: true } } } } }, orderBy: { number: "asc" } } },
  });
  const table = await standings(tournamentId);

  const doc = new PDFDocument({ size: "A4", margin: 40 });
  const chunks: Buffer[] = [];
  doc.on("data", (c: Buffer) => chunks.push(c));
  const done = new Promise<Buffer>((resolve) => doc.on("end", () => resolve(Buffer.concat(chunks))));

  // Header
  doc.fontSize(20).font("Helvetica-Bold").text(t.name);
  doc.fontSize(10).font("Helvetica").fillColor("#555")
     .text(`${t.club.name} · ${t.format} · ${t.timeControlDetail ?? t.timeControl} · Round ${t.currentRound}/${t.totalRounds}`);
  doc.moveDown();

  // Current round pairing sheet
  const current = t.rounds.find((r) => r.number === t.currentRound);
  if (current) {
    doc.fillColor("#000").fontSize(14).font("Helvetica-Bold").text(`Round ${current.number} Pairings`);
    doc.moveDown(0.4);
    doc.fontSize(10).font("Helvetica");
    for (const m of current.matches.sort((a, b) => a.boardNumber - b.boardNumber)) {
      const w = m.white?.profile?.fullName ?? "—";
      const b = m.black ? m.black.profile?.fullName ?? "—" : "BYE";
      const res = m.result === "PENDING" ? "____ – ____" : formatResult(m.result);
      doc.text(`Board ${String(m.boardNumber).padStart(2)}   ${w.padEnd(28)} vs ${b.padEnd(28)} ${res}`);
    }
    doc.moveDown();
  }

  // Standings wallchart
  doc.fontSize(14).font("Helvetica-Bold").text("Standings");
  doc.moveDown(0.4);
  doc.fontSize(9).font("Helvetica-Bold")
     .text("Rk   Player                          Pts    Buch    SB", { continued: false });
  doc.font("Helvetica");
  for (const s of table) {
    doc.text(
      `${String(s.rank).padStart(2)}   ${(s.player?.fullName ?? s.userId).padEnd(30)} ${s.score.toFixed(1).padStart(4)}  ` +
      `${s.tiebreaks.BUCHHOLZ.toFixed(1).padStart(6)}  ${s.tiebreaks.SONNEBORN_BERGER.toFixed(2).padStart(6)}`
    );
  }

  doc.fontSize(7).fillColor("#999").text(`Generated by Glyph · ${new Date().toISOString()}`, 40, 800);
  doc.end();
  return done;
}

function formatResult(r: string): string {
  switch (r) {
    case "WHITE_WIN": case "BLACK_FORFEIT": return "1 – 0";
    case "BLACK_WIN": case "WHITE_FORFEIT": return "0 – 1";
    case "DRAW": return "½ – ½";
    case "BYE_FULL": return "1 (bye)";
    case "BYE_HALF": return "½ (bye)";
    default: return "";
  }
}
